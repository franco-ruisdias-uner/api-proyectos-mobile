/** Un tramo por cada día de la lista (R2). */
function tramo(
  dias: Dia[],
  abre: string,
  cierra: string,
  temporada: Temporada = 'todo-el-anio',
): HorarioConTemporada[] {
  return dias.map((dia) => ({ dia, abre, cierra, temporada }));
}

